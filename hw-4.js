// С помощью вложенных циклов создайте многомерный массив вида: 
// [[1, 1, 1], [1, 1, 1], [1, 1, 1]].


let numbers = []; // 1. Инициализируем основной массив

for (let i = 0; i < 3; i++) {
  numbers[i] = []; // 2. Создаем подмассив для каждой строки
  for (let j = 0; j < 3; j++) {
    numbers[i][j] = 1; // Заполняем подмассив единицами
  }
}

console.log(numbers); // [[1, 1, 1], [1, 1, 1], [1, 1, 1]]